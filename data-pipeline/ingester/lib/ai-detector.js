import { extractTexts } from './tag-extractor.js';

// Best-effort heuristic — documented as directional, not precise.
const AI_LOGIN_RE = /\b(copilot|claude|codex|aider|cursor|devin|cody|sweep|gpt[-_]?engineer)\b|\[bot\]$/i;
const AI_MESSAGE_RE = /co-authored-by:\s*(claude|copilot|codex|cursor|devin|cody|gpt|aider)|generated by (claude|copilot|cursor)|🤖|🦾/i;

export function detectAI(event) {
  const actor = event.actor ?? {};

  // actor.type === 'Bot' is the strongest signal
  if (actor.type === 'Bot') return true;

  // [bot] suffix in login
  if (actor.login && AI_LOGIN_RE.test(actor.login)) return true;

  // AI co-authorship or generation signatures in event text fields
  const texts = extractTexts(event);
  for (const text of texts) {
    if (AI_MESSAGE_RE.test(text)) return true;
  }

  return false;
}
